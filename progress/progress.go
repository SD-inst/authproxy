type ProgressUpdate struct {
	Queued       int       `json:"queued"`
	Current      int       `json:"current"`
	Progress     float64   `json:"progress"`
	ETA          string    `json:"eta"`
	Description  string    `json:"description"`
	LastActive   time.Time `json:"last_active"`
	TaskDuration string    `json:"duration"`
	// Color is the display color configured for the user that queued the most
	// recent task ("" = the page default). It lingers after the task ends until
	// another task replaces it. The username itself stays server-side; the
	// color is what makes a non-default user visible.
	Color string `json:"color"`
	// Indeterminate is true while the LLM holds the slot: a generation has no
	// progress fraction (llama.cpp never reports how far it has got), so the
	// page draws the bar full with animated diagonal stripes and the token
	// count in the description is what shows the task is alive.
	Indeterminate bool `json:"indeterminate"`
}

type GPUUpdate struct {
	Used  uint64 `json:"used"`
	Free  uint64 `json:"free"`
	Total uint64 `json:"total"`
}

type sdprogressState struct {
	JobTimestamp  string  `json:"job_timestamp"`
	Job           *string `json:"job"`
	Node          string  `json:"node"`
	JobCount      int     `json:"job_count"`
	SamplingSteps int     `json:"sampling_steps"`
	SamplingStep  int     `json:"sampling_step"`
}

type sdprogress struct {
	Progress    float64 `json:"progress"`
	EtaRelative float64 `json:"eta_relative"`
	QueueSize   int     `json:"queue_size"`
	State       sdprogressState
}

// TaskColorSetter lets callers (the queue join and job_start handlers) apply
// the display color of the user who queued the current task, so the status
// page can color its progress bar ("" = the default). The username itself is
// resolved server-side and never sent to the page.
type TaskColorSetter interface {
	SetTaskColor(color string)
}

// TokenReporter lets the LLM balancer credit output tokens generated by the
// current request to the status page, naming the model that produced them. An
// LLM generation has no progress percentage, so the growing token count (shown
// in the description together with the model) is the only signal that the task
// is running rather than hung.
type TokenReporter interface {
	AddTokens(model string, tokens uint64)
}

// QueueControls is the control surface the service queue join handlers use:
// setting the current task's color and resetting the CUI progress state at
// task start (ComfyUI does not send a zero-progress on task start). Passing
// this instead of the unexported progress type keeps the handlers decoupled.
type QueueControls interface {
	TaskColorSetter
	TokenReporter
	ResetCUI()
}

type progress struct {
	b             *events.Broker
	sdhost        string
	wd            *watchdog.Watchdog
	timeout       time.Duration
	m             chan<- metrics.MetricUpdate
	svcChan       <-chan servicequeue.SvcUpdate
	pchan         chan sdprogress
	statusToken   string
	sq            *servicequeue.ServiceQueue
	resetCUI      chan struct{}
	resetProgress chan servicequeue.SvcType
	startJob      chan servicequeue.SvcType
	colorChan     chan string
	// llmTokens accumulates the output tokens credited by AddTokens since the
	// slot was acquired; llmModel holds the model that produced the most recent
	// credit. tokenTick is the (coalescing) wake-up for the updater to re-read
	// both. They are reset when the slot is acquired and when it is freed.
	llmTokens atomic.Uint64
	llmModel  atomic.Value
	tokenTick chan struct{}
}

func NewProgress(broker *events.Broker, sdhost string, timeout int, wd *watchdog.Watchdog, m chan<- metrics.MetricUpdate, svcChan <-chan servicequeue.SvcUpdate, statusToken string, sq *servicequeue.ServiceQueue) *progress {
	return &progress{b: broker, sdhost: sdhost, timeout: time.Second * time.Duration(timeout), wd: wd, m: m, svcChan: svcChan, pchan: make(chan sdprogress, 100), statusToken: statusToken, sq: sq, resetCUI: make(chan struct{}, 1), resetProgress: make(chan servicequeue.SvcType, 1), startJob: make(chan servicequeue.SvcType, 1), colorChan: make(chan string, 1), tokenTick: make(chan struct{}, 1)}
}

// SetTaskColor applies the display color of the user who queued the task
// currently holding the service slot ("" = the page default). The color is
// applied asynchronously by the updater and broadcast with the next progress
// packet. It lingers after the task ends and is replaced only by the next
// task's color. Non-blocking: the latest call wins under a race.
func (p *progress) SetTaskColor(color string) {
	select {
	case p.colorChan <- color:
	default:
	}
}

// AddTokens credits output tokens generated by the current LLM request, naming
// the model that generated them. The counter accumulates until the slot is
// freed; the updater re-reads the pair (so a coalesced wake-up never loses a
// delta) and shows it as the task line.
func (p *progress) AddTokens(model string, tokens uint64) {
	if tokens == 0 {
		return
	}
	if model != "" {
		p.llmModel.Store(model)
	}
	p.llmTokens.Add(tokens)
	select {
	case p.tokenTick <- struct{}{}:
	default:
	}
}

// tokenLine is the LLM task line: the model that generated plus the number of
// output tokens. A generation reports no percentage, so this line is what
// shows the task is alive rather than hung.
func tokenLine(model string, tokens uint64) string {
	if model == "" {
		return fmt.Sprintf("%d tokens generated", tokens)
	}
	return fmt.Sprintf("%s: %d tokens generated", model, tokens)
}

// ResetCUI resets the CUI progress state and all ETA timers at task start
// (ComfyUI does not send a zero-progress on task start, so the previous
// task's 100% would otherwise linger until the next sampler's first step).
// Non-blocking: if the updater is already resetting, the signal is dropped.
func (p *progress) ResetCUI() {
	select {
	case p.resetCUI <- struct{}{}:
	default:
	}
}

func (p *progress) updater() {
	lastProgress := float64(0)
	lastID := ""
	jobStart := time.Time{}
	// lastTaskDuration holds the frozen duration of the most recently
	// completed task. It is shown (via broadcast) once a job ends and there is
	// no active baseline, so the UI still knows how long the last task took.
	lastTaskDuration := time.Duration(0)
	nodeStart := time.Time{}
	adjustedNodeStart := time.Time{}
	lastNode := ""
	lastCUI := false
	nodeRefStart := time.Time{}      // last progress of the previous node (gap reference)
	prevNodeRate := time.Duration(0) // per-step rate of the previous node (first-step prior)
	nodeStartValue := 0
	lastMax := 0
	lastStep := 0
	lastStepTs := time.Time{}
	stepObs := 0
	lastProgTs := time.Time{}
	lastJobCount := 0
	lastQueue := 0
	lastProg := float64(0)
	// curColor is the display color of the user whose task last held the slot
	// (set via SetTaskColor from the join/job_start handlers). Like the task
	// line it outlives the task: it is replaced by the next task's color (which
	// is the default "" for a user without a configured one), never cleared
	// when the slot is freed. The username itself is never broadcast.
	curColor := ""
	// curSvc is the service currently holding the slot (NONE/WAIT = nobody).
	// It drives the LLM's indeterminate bar (a generation reports no progress
	// fraction) and the token counter.
	curSvc := servicequeue.NONE
	// taskDesc is the progress-level task line ("rendering 12/20 steps",
	// "magnum-v4-12b-Q8_0-HF: 231 tokens generated"). It is sticky: every
	// broadcast carries it, so a per-second ETA tick never wipes the line, and
	// it outlives the task (through the grace window and after the slot is
	// freed) until the next task replaces it. The page and status.json fall
	// back to the service-level description (the model name) when it is empty.
	taskDesc := ""
	// jobActive is true while a job is running (service not NONE). It gates the
	// ticker: after the service drops to NONE (resetProgress) it is cleared so
	// the frozen duration/last_active no longer tick. It also marks a finished
	// task: on the drop to WAIT/NONE it credits GPU_ACTIVE_TIME and, being
	// cleared after the first WAIT/NONE, ensures a task is counted once (the
	// follow-on WAIT->NONE is not double-counted). Unlike lastID, it does not
	// linger past completion (lastID is kept for the GPU_ACTIVE_TIME metric).
	jobActive := false
	ticker := time.NewTicker(time.Second)
	defer ticker.Stop()

	// Remaining ETA, computed over the same span the progress fraction covers.
	//
	// CUI (ComfyUI): progress is per-node (value/max resets each node), and
	// nodeStart is the FIRST progress of the node — which arrives after step
	// nodeStartValue (usually 1). So the elapsed span covers (lastStep -
	// nodeStartValue) steps, not lastStep; the rate is measured over that span
	// and remaining is (lastMax - lastStep) steps at that rate. This keeps the
	// ETA stable from the second step on (like CozyUI).
	//
	// A1111 (SDF): no node id, progress is the job-wide fraction, so the
	// baseline is jobStart and the rate is over the whole job (batch-wide
	// progress; the per-task sampling_step would make the ETA jump). The first
	// increment (often model loading) is re-timed via adjustedNodeStart.
	//
	// The estimate is aged down each second until the next update. ok=false
	// when there is no baseline yet.
	computeEta := func(now time.Time) (time.Duration, bool) {
		if lastProgTs.IsZero() {
			return 0, false
		}
		var elapsed time.Duration
		var remaining time.Duration
		if lastCUI {
			units := lastStep - nodeStartValue
			if units < 0 {
				return 0, false
			}
			if units == 0 {
				// Only the first step is known and there is no measured span
				// yet. Estimate the first step's duration: prefer the previous
				// node's per-step rate (a typical step time, excludes setup);
				// fall back to the gap to the previous event capped at 60s
				// (the gap includes setup time, so it overestimates).
				// Corrects on the second step.
				var stepEst time.Duration
				if prevNodeRate > 0 {
					stepEst = prevNodeRate
				} else if !nodeRefStart.IsZero() {
					stepEst = min(nodeStart.Sub(nodeRefStart), 60*time.Second)
				}
				if stepEst <= 0 {
					return 0, false
				}
				remaining = time.Duration(float64(stepEst) * float64(lastMax-lastStep))
			} else {
				elapsed = lastProgTs.Sub(nodeStart)
				if elapsed <= 0 {
					return 0, false
				}
				remaining = time.Duration(float64(elapsed) / float64(units) * float64(lastMax-lastStep))
			}
		} else {
			if lastProg <= 0 || lastProg >= 1 {
				return 0, false
			}
			start := jobStart
			if !adjustedNodeStart.IsZero() {
				start = adjustedNodeStart
			}
			elapsed = lastProgTs.Sub(start)
			if elapsed <= 0 {
				return 0, false
			}
			remaining = time.Duration(float64(elapsed) * (1 - lastProg) / lastProg)
		}
		age := now.Sub(lastProgTs)
		if age < 0 {
			age = 0
		}
		eta := remaining - age
		if eta < 0 {
			eta = 0
		}
		return eta, true
	}

	broadcast := func() {
		now := time.Now()
		etaStr := ""
		if eta, ok := computeEta(now); ok {
			etaStr = eta.Truncate(time.Second).String()
		}
		// The LLM generation is the one task that has no progress fraction, so
		// the packet marks it indeterminate and reports a full bar: the page
		// draws it as a full bar with animated diagonal stripes.
		indeterminate := curSvc == servicequeue.LLM
		prog := lastProg
		if indeterminate {
			prog = 1
		}
		// Duration is only meaningful once a job has a start: jobStart is set
		// when the service takes the slot (and by a CUI reset). Before the
		// first transition it is the zero time and now.Sub would yield a bogus
		// multi-year value, so leave it blank.
		dur := ""
		if !jobStart.IsZero() {
			dur = now.Sub(jobStart).Truncate(time.Second).String()
		} else if lastTaskDuration > 0 {
			// No active job: keep showing the last completed task's duration so
			// the UI still knows how long the most recent task took.
			dur = lastTaskDuration.Truncate(time.Second).String()
		}
		p.b.Broadcast(events.Packet{
			Type: events.PROGRESS_UPDATE,
			Data: ProgressUpdate{
				Current:       lastJobCount,
				Queued:        lastQueue,
				Progress:      prog,
				ETA:           etaStr,
				Description:   taskDesc,
				LastActive:    now,
				TaskDuration:  dur,
				Color:         curColor,
				Indeterminate: indeterminate,
			}})
	}

	for {
		select {
		case c := <-p.colorChan:
			curColor = c
			broadcast()
		case <-p.resetCUI:
			// Task start: ComfyUI does not send zero-progress here, so clear
			// the previous task's state and all ETA baselines (the progress
			// would otherwise linger at 100% until the next sampler step).
			lastProg = 0
			lastProgTs = time.Time{}
			jobStart = time.Now()
			lastID = ""
			nodeStart = time.Time{}
			adjustedNodeStart = time.Time{}
			lastNode = ""
			lastCUI = false
			nodeRefStart = time.Time{}
			prevNodeRate = 0
			nodeStartValue = 0
			lastMax = 0
			lastStep = 0
			lastStepTs = time.Time{}
			stepObs = 0
			jobActive = false
			p.llmTokens.Store(0)
			p.llmModel.Store("")
			taskDesc = ""
			broadcast()
		case svc := <-p.resetProgress:
			// The service dropped to NONE or WAIT: the active job (if any) just
			// ended. Count it as a completed task (regardless of service type) and
			// credit its duration to GPU_ACTIVE_TIME before clearing the baseline.
			// Guarding on jobActive skips a bare NONE->active->NONE blip, and
			// clearing it below keeps the follow-on WAIT->NONE from counting twice.
			if jobActive {
				p.m <- metrics.MetricUpdate{Type: metrics.TASKS_COMPLETED, Value: 1}
				if !jobStart.IsZero() {
					lastTaskDuration = time.Since(jobStart)
					p.m <- metrics.MetricUpdate{Type: metrics.GPU_ACTIVE_TIME, Value: lastTaskDuration.Seconds()}
				}
			}
			curSvc = svc
			lastProg = 0
			lastProgTs = time.Time{}
			jobStart = time.Time{}
			jobActive = false
			lastJobCount = 0
			// The task line and the color are kept: they record what the task
			// just did (the generated-token count of the last LLM generation,
			// the last step count) and whose it was, and the next task replaces
			// both. Clearing them here made the count and the bar color vanish
			// the moment the generation ended.
			broadcast()
		case svc := <-p.startJob:
			// Service transitioned from NONE/WAIT to an active service:
			// start the duration timer.
			curSvcWas := curSvc
			curSvc = svc
			jobStart = time.Now()
			jobActive = true
			// A request holds the slot from here on: services that never report
			// a job count (the LLM, TTS) would otherwise leave "Tasks: 0" while
			// their request runs. A1111 and ComfyUI refine it from their
			// progress stream on the next update.
			lastJobCount = 1
			// A chained LLM request (WAIT -> LLM inside the grace window) is a
			// continuation of the same working session: an agent's back-to-back
			// requests must not blank the token line or restart the count. A
			// fresh acquisition (from NONE) or another service starts clean.
			if svc != servicequeue.LLM || curSvcWas != servicequeue.WAIT {
				taskDesc = ""
				p.llmTokens.Store(0)
				p.llmModel.Store("")
			}
			// Announce the start right away: a service that reports no progress
			// (the LLM) would otherwise leave the page waiting up to a second
			// for the next ETA tick to learn the task began.
			broadcast()
		case <-p.tokenTick:
			// The LLM credited more output tokens; the row that carried them
			// names the model that generated them. A generation reports no
			// percentage, so this line is what shows the task is alive rather
			// than hung, and it usually lands right as the generation ends.
			// Both values are re-read whole on every wake-up, so a coalesced
			// burst of updates still reports the exact total.
			model, _ := p.llmModel.Load().(string)
			taskDesc = tokenLine(model, p.llmTokens.Load())
			broadcast()
		case sdp := <-p.pchan:
			if sdp.State.Job == nil {
				continue
			}
			if lastID != *sdp.State.Job {
				// The previous job ended because this new one replaced it (CUI
				// keeps the slot without a NONE between jobs). Credit its duration
				// first; jobStart holds when it began. If the job already ended
				// via NONE/WAIT, jobStart was zeroed there and this is skipped, so
				// a job is never credited twice.
				if lastID != "" && !jobStart.IsZero() {
					lastTaskDuration = time.Since(jobStart)
					p.m <- metrics.MetricUpdate{Type: metrics.GPU_ACTIVE_TIME, Value: lastTaskDuration.Seconds()}
				}
				if *sdp.State.Job != "" {
					jobStart = time.Now()
					jobActive = true
				} else {
					jobStart = time.Time{}
					jobActive = false
				}
				lastID = *sdp.State.Job
			}
			// Node boundary: ComfyUI sends a per-node id (value/max resets each
			// node), so the ETA baseline is re-timed on every node. A1111 has
			// no node id, so the job name stays the boundary (SDF behaviour is
			// unchanged).
			nodeKey := *sdp.State.Job
			if sdp.State.Node != "" {
				nodeKey = sdp.State.Node
			}
			if lastNode != nodeKey {
				if nodeKey != "" {
					// Capture the previous node's last progress time (gap
					// reference) and per-step rate (first-step prior).
					nodeRefStart = lastProgTs
					if pu := lastStep - nodeStartValue; pu > 0 && !nodeStart.IsZero() && !lastProgTs.IsZero() {
						prevNodeRate = lastProgTs.Sub(nodeStart) / time.Duration(pu)
					} else {
						prevNodeRate = 0
					}
					nodeStart = time.Now()
					nodeStartValue = sdp.State.SamplingStep // first progress of the node (usually step 1)
					adjustedNodeStart = time.Time{}
					lastStep = 0
					lastStepTs = time.Time{}
					stepObs = 0
					lastProgTs = time.Time{}
					lastProg = -1
				}
				lastNode = nodeKey
			}
			lastCUI = sdp.State.Node != ""
			lastMax = sdp.State.SamplingSteps
			lastJobCount = sdp.State.JobCount
			lastQueue = sdp.QueueSize
			if sdp.Progress != lastProg {
				lastProgTs = time.Now()
			}
			lastProg = sdp.Progress
			if sdp.State.SamplingStep != lastStep {
				now := time.Now()
				if sdp.State.SamplingStep > lastStep {
					stepObs++
					// The first observed increment often includes model
					// loading. On the second observation, re-time it to the
					// second's per-step rate when that is significantly
					// faster (10% threshold), regardless of how many steps
					// each poll jumped.
					if stepObs == 2 {
						firstDur := lastStepTs.Sub(nodeStart)
						secondDur := now.Sub(lastStepTs)
						if firstDur > 0 && secondDur > 0 {
							firstRate := firstDur / time.Duration(lastStep)
							secondRate := secondDur / time.Duration(sdp.State.SamplingStep-lastStep)
							if secondRate > 0 && 10*secondRate <= 9*firstRate {
								adjustedNodeStart = nodeStart.Add(firstDur - time.Duration(lastStep)*secondRate)
							}
						}
					}
				}
				lastStep = sdp.State.SamplingStep
				lastStepTs = now
			}
			if lastProgress != sdp.Progress {
				desc := fmt.Sprintf("%s %d/%d steps", "rendering", sdp.State.SamplingStep, sdp.State.SamplingSteps)
				// The step line becomes the sticky task line. When the slot is
				// already gone (UpdateProgressDescription refuses) there is no
				// task to describe, so the line is dropped instead.
				if p.sq.UpdateProgressDescription(desc) {
					taskDesc = desc
				} else {
					taskDesc = ""
				}
				broadcast()
				lastProgress = sdp.Progress
				p.m <- metrics.MetricUpdate{Type: metrics.QUEUE_LENGTH, Value: float64(sdp.QueueSize)}
			}
			if p.wd != nil && time.Since(jobStart) > p.timeout && sdp.Progress > 0 {
				log.Printf("Task execution time exceeded %s, restarting", p.timeout.String())
				p.wd.Send("restart stablediff-cuda")
			}
		case <-ticker.C:
			// Tick the ETA/duration down each second while a job is running.
			// Stops once the service drops to NONE (jobActive cleared in
			// resetProgress), so the final duration/last_active freeze.
			if jobActive {
				broadcast()
			}
		}
	}
}

func (p *progress) gpuStatus() {
	cmd := exec.Command("nvidia-smi", "--query-gpu", "memory.used,memory.free,memory.total,power.draw", "--format", "csv,noheader,nounits", "-l", "1")
	output, err := cmd.StdoutPipe()
	if err != nil {
		log.Printf("Error getting stdout of nvidia-smi: %s", err)
		return
	}
	s := bufio.NewScanner(output)
	if err := cmd.Start(); err != nil {
		log.Printf("Error starting nvidia-smi: %s", err)
		return
	}
	for s.Scan() {
		line := s.Text()
		split := strings.Split(line, ", ")
		if len(split) < 4 {
			log.Printf("GPU monitoring error, read line: %s", line)
			return
		}
		used, _ := strconv.ParseUint(split[0], 10, 64)
		free, _ := strconv.ParseUint(split[1], 10, 64)
		total, _ := strconv.ParseUint(split[2], 10, 64)
		watts, _ := strconv.ParseFloat(split[3], 64)
		p.b.Broadcast(events.Packet{Type: events.GPU_UPDATE, Data: GPUUpdate{Free: free, Used: used, Total: total}})
		p.m <- metrics.MetricUpdate{Type: metrics.GPU_FREE_MEMORY, Value: float64(free)}
		p.m <- metrics.MetricUpdate{Type: metrics.GPU_USED_MEMORY, Value: float64(used)}
		p.m <- metrics.MetricUpdate{Type: metrics.GPU_JOULES_SPENT, Value: float64(watts)}
	}
	if err := s.Err(); err != nil {
		log.Printf("Error scanning nvidia-smi output: %s", err)
	}
	cmd.Wait()
}

func (p *progress) serviceUpdater() {
	var lastDescription string
	var lastPrevService servicequeue.SvcType
	var lastPrevWaitService servicequeue.SvcType
	var prevSvcType servicequeue.SvcType
	for svc := range p.svcChan {
		if svc.Type == servicequeue.NONE || svc.Type == servicequeue.WAIT {
			// Service is NONE or WAIT: no active job, so reset the progress.
			// Non-blocking: if the updater is already resetting, drop it.
			select {
			case p.resetProgress <- svc.Type:
			default:
			}
		} else if prevSvcType == servicequeue.NONE || prevSvcType == servicequeue.WAIT {
			// Transitioned from NONE/WAIT to an active service: start the timer.
			select {
			case p.startJob <- svc.Type:
			default:
			}
		}
		prevSvcType = svc.Type
		resp := p.b.State(events.SERVICE_UPDATE)
		event := events.ServiceUpdate{Service: svc.Type, WaitService: svc.WaitType, LastActive: time.Now(), Queue: svc.Queue}
		if svc.Description != "" {
			event.Description = svc.Description
			lastDescription = svc.Description
		} else if pkt, ok := resp.(events.Packet); ok && pkt.Type == events.SERVICE_UPDATE {
			if prevSvc, ok := pkt.Data.(events.ServiceUpdate); ok {
				event.Description = prevSvc.Description
			}
		} else {
			event.Description = lastDescription
		}
		if pkt, ok := resp.(events.Packet); ok && pkt.Type == events.SERVICE_UPDATE {
			prevSvc := pkt.Data.(events.ServiceUpdate)
			if svc.Type == servicequeue.IGNORE {
				event.Service = prevSvc.Service
				svc.Type = prevSvc.Service
			}
			if prevSvc.Service != svc.Type {
				event.PrevService = prevSvc.Service
				event.PrevWaitService = prevSvc.WaitService
			} else {
				event.PrevService = lastPrevService
				event.PrevWaitService = lastPrevWaitService
			}
		}
		lastPrevService = event.PrevService
		lastPrevWaitService = event.PrevWaitService
		p.b.Broadcast(events.Packet{Type: events.SERVICE_UPDATE, Data: event})
	}
}

func (p *progress) sdQuery(sq *servicequeue.ServiceQueue) {
	client := http.Client{Timeout: time.Second * 5}
	for {
		time.Sleep(time.Second)
		sq.Lock()
		sq.AwaitCheck(servicequeue.SD, true, false, nil)
		sq.Unlock()
		resp, err := client.Get(p.sdhost + "/sdapi/v1/progress")
		if err != nil {
			continue
		}
		var sdp sdprogress
		json.NewDecoder(resp.Body).Decode(&sdp)
		p.pchan <- sdp
	}
}

func (p *progress) handleCUIProgress(c echo.Context) error {
	var params struct {
		Value float64 `json:"value"`
		Max   float64 `json:"max"`
		Queue int     `json:"queue"`
		Job   string  `json:"prompt_id"`
		Node  string  `json:"node"`
	}
	c.Bind(&params)
	p.pchan <- sdprogress{Progress: params.Value / params.Max, QueueSize: params.Queue - 1, State: sdprogressState{Job: &params.Job, Node: params.Node, SamplingSteps: int(params.Max), SamplingStep: int(params.Value), JobCount: 1}}
	p.sq.SetService(servicequeue.CUI, fmt.Sprintf("rendering %d/%d steps", int(params.Value), int(params.Max)))
	return nil
}

type statusJSON struct {
	Description     string  `json:"description"`
	Progress        float64 `json:"progress"`
	Indeterminate   bool    `json:"indeterminate"`
	TaskQueue       int     `json:"task_queue"`
	ServiceQueue    int32   `json:"service_queue"`
	Service         string  `json:"service"`
	WaitService     string  `json:"wait_service"`
	PrevService     string  `json:"prev_service"`
	PrevWaitService string  `json:"prev_wait_service"`
	ETA             string  `json:"eta"`
	Color           string  `json:"color"`
}

func (p *progress) handleStatusJSON(c echo.Context) error {
	if p.statusToken != "" {
		token := c.QueryParam("token")
		if token != p.statusToken {
			return c.JSON(http.StatusUnauthorized, map[string]string{"error": "unauthorized"})
		}
	}

	var description string
	var progProgress float64
	var progQueued int
	var progETA string
	var progColor string
	var progIndeterminate bool

	progResp := p.b.State(events.PROGRESS_UPDATE)
	if progResp != nil {
		if pkt, ok := progResp.(events.Packet); ok {
			if pu, ok := pkt.Data.(ProgressUpdate); ok {
				progProgress = pu.Progress
				progQueued = pu.Queued
				progETA = pu.ETA
				description = pu.Description
				progColor = pu.Color
				progIndeterminate = pu.Indeterminate
			}
		}
	}

	var svcQueue int32
	var svcName string
	var waitSvcName string
	var prevSvcName string
	var prevWaitSvcName string
	var su events.ServiceUpdate

	svcResp := p.b.State(events.SERVICE_UPDATE)
	if svcResp != nil {
		if pkt, ok := svcResp.(events.Packet); ok {
			if suData, ok := pkt.Data.(events.ServiceUpdate); ok {
				su = suData
				svcQueue = su.Queue
				svcName = su.Service.String()
				waitSvcName = su.WaitService.String()
				prevSvcName = su.PrevService.String()
				prevWaitSvcName = su.PrevWaitService.String()
			}
		}
	}

	// Two description levels exist: the progress-level one is the live task
	// line ("rendering 12/20 steps", "231 tokens generated") and is empty
	// between updates; the service-level one is persistent per service (the LLM
	// model name, "working"). The live line wins while it is set, otherwise the
	// service description shows. The page applies the same precedence.
	if description == "" {
		description = su.Description
	}

	return c.JSON(http.StatusOK, statusJSON{
		Description:     description,
		Progress:        progProgress,
		Indeterminate:   progIndeterminate,
		TaskQueue:       progQueued,
		ServiceQueue:    svcQueue,
		Service:         svcName,
		WaitService:     waitSvcName,
		PrevService:     prevSvcName,
		PrevWaitService: prevWaitSvcName,
		ETA:             progETA,
		Color:           progColor,
	})
}

func (p *progress) Start(sq *servicequeue.ServiceQueue) {
	go p.b.Start(context.Background())
	go p.updater()
	go p.sdQuery(sq)
	go p.gpuStatus()
	go p.serviceUpdater()
}

func (p *progress) AddHandlers(e *echo.Echo) {
	root, err := fs.Sub(webroot, "webroot")
	if err != nil {
		log.Fatal(err)
	}
	e.GET("/q/*", echo.StaticDirectoryHandler(root, false))
	e.GET("/q/ws", p.b.WSHandler)
	e.GET("/q/status.json", p.handleStatusJSON)
	e.POST("/cui/progress", p.handleCUIProgress)
}
